-- 2.1 Query base da página IoT (src/frontend/pages/iot.py::_load_oracle)
-- Consulta direta da tabela operacional usada no dashboard.
SELECT * FROM SENSORES_FARMTECH;

-- 2.2 Últimos registros IoT (inspeção rápida)
SELECT *
FROM SENSORES_FARMTECH
ORDER BY INSTANTE DESC
FETCH FIRST 10 ROWS ONLY;

-- 2.3 Base para Notebook ML / aba Notebook ML
SELECT UMIDADE, TEMP_C, PH_CORR, N, P, K, BOMBA_FW
FROM SENSORES_FARMTECH;

-- 2.4 Query base de clima para análises e cruzamentos com IoT
SELECT h.DT_FORECAST,
       h.NR_TEMPERATURE_2M,
       h.NR_HUMIDITY,
       h.NR_PRECIPITATION,
       h.NR_PRECIP_PROB,
       h.NR_CLOUDCOVER,
       h.NR_WINDSPEED_10M,
       h.NR_UV_INDEX,
       h.NR_WEATHERCODE,
       l.NM_CITY
FROM WTH_HOURLY_FORECAST h
JOIN WTH_LOCATIONS l ON l.ID_LOCATION = h.ID_LOCATION
ORDER BY h.DT_FORECAST;

-- 2.5 Total de registros importados (sanidade rápida)
SELECT COUNT(*) AS TOTAL FROM SENSORES_FARMTECH;

-- 2.6 Contagem de timestamps preenchidos (sanidade do trigger)
SELECT COUNT(*) AS COM_INSTANTE
FROM SENSORES_FARMTECH
WHERE INSTANTE IS NOT NULL;

-- 2.7 Estatísticas descritivas alinhadas ao schema atual
SELECT
    ROUND(AVG(UMIDADE),2) AS MEDIA_UMIDADE, MIN(UMIDADE) AS MIN_UMIDADE, MAX(UMIDADE) AS MAX_UMIDADE,
    ROUND(AVG(TEMP_C),2)  AS MEDIA_TEMP_C,  MIN(TEMP_C)  AS MIN_TEMP_C,  MAX(TEMP_C)  AS MAX_TEMP_C,
    ROUND(AVG(PH_CORR),2) AS MEDIA_PH_CORR, MIN(PH_CORR) AS MIN_PH_CORR, MAX(PH_CORR) AS MAX_PH_CORR
FROM SENSORES_FARMTECH;

-- 2.8 Contagem por estado de irrigação (bomba)
SELECT BOMBA_FW,
       DECODE(BOMBA_FW, 1, 'Ligada', 0, 'Desligada', '?') AS STATUS,
       COUNT(*)                                            AS QUANTIDADE,
       ROUND(COUNT(*) * 100 / SUM(COUNT(*)) OVER(), 2)    AS PERCENTUAL
FROM SENSORES_FARMTECH
GROUP BY BOMBA_FW;

-- 2.9 Solo seco (umidade < 40)
SELECT *
FROM SENSORES_FARMTECH
WHERE UMIDADE < 40
ORDER BY UMIDADE;

-- 2.10 pH fora da faixa ideal (6.0 a 7.0)
SELECT *
FROM SENSORES_FARMTECH
WHERE PH_CORR < 6.0 OR PH_CORR > 7.0
ORDER BY PH_CORR;

-- 2.11 Condição crítica (solo seco + pH fora + bomba desligada)
SELECT *
FROM SENSORES_FARMTECH
WHERE UMIDADE < 40
  AND (PH_CORR < 6.0 OR PH_CORR > 7.0)
  AND BOMBA_FW = 0;

-- 2.12 NPK simultâneo presente
SELECT *
FROM SENSORES_FARMTECH
WHERE N = 1 AND P = 1 AND K = 1;

-- 2.13 Médias NPK por estado da bomba
SELECT BOMBA_FW,
       DECODE(BOMBA_FW, 1, 'Ligada', 'Desligada') AS BOMBA,
       ROUND(AVG(UMIDADE),2) AS MEDIA_UMIDADE,
       ROUND(AVG(TEMP_C),2)  AS MEDIA_TEMP_C,
       ROUND(AVG(PH_CORR),2) AS MEDIA_PH_CORR,
       ROUND(AVG(N),3)       AS MEDIA_N,
       ROUND(AVG(P),3)       AS MEDIA_P,
       ROUND(AVG(K),3)       AS MEDIA_K
FROM SENSORES_FARMTECH
GROUP BY BOMBA_FW;
