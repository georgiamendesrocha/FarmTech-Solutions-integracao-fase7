-- MÓDULO 1 — PREVISÃO DO TEMPO (Open-Meteo / Pato Branco)
-- ══════════════════════════════════════════════════════════════

-- 1.1 Condição atual (última hora coletada)
SELECT h.*
FROM WTH_HOURLY_FORECAST h
WHERE h.ID_LOCATION = :id_location
  AND h.DT_FORECAST = (
      SELECT MAX(DT_FORECAST) FROM WTH_HOURLY_FORECAST
      WHERE ID_LOCATION = :id_location AND DT_FORECAST <= SYSTIMESTAMP);

-- 1.2 Previsão horária — próximas 24h
SELECT DT_FORECAST, NR_TEMPERATURE_2M, NR_APPARENT_TEMP, NR_HUMIDITY,
       NR_PRECIPITATION, NR_PRECIP_PROB, NR_WEATHERCODE,
       NR_WINDSPEED_10M, NR_CLOUDCOVER, NR_UV_INDEX
FROM WTH_HOURLY_FORECAST
WHERE ID_LOCATION = :id_location
  AND DT_FORECAST BETWEEN SYSTIMESTAMP
      AND SYSTIMESTAMP + NUMTODSINTERVAL(24, 'HOUR')
ORDER BY DT_FORECAST;

-- 1.3 Previsão diária — próximos 7 dias
SELECT DT_FORECAST, NR_TEMP_MAX, NR_TEMP_MIN, NR_PRECIP_SUM,
       NR_PRECIP_PROB_MAX, NR_WINDSPEED_MAX, NR_UV_MAX,
       NR_WEATHERCODE, NR_SUNRISE, NR_SUNSET
FROM WTH_DAILY_FORECAST
WHERE ID_LOCATION = :id_location
  AND DT_FORECAST BETWEEN TRUNC(SYSDATE) AND TRUNC(SYSDATE) + 6
ORDER BY DT_FORECAST;

-- 1.4 Médias mensais (últimos 12 meses)
SELECT TO_CHAR(DT_FORECAST,'YYYY-MM')       AS MES,
       ROUND(AVG(NR_TEMPERATURE_2M),2)      AS TEMP_MEDIA,
       ROUND(MAX(NR_TEMPERATURE_2M),2)      AS TEMP_MAX,
       ROUND(MIN(NR_TEMPERATURE_2M),2)      AS TEMP_MIN,
       ROUND(AVG(NR_HUMIDITY),2)            AS UMIDADE_MEDIA,
       ROUND(SUM(NR_PRECIPITATION),2)       AS PRECIP_TOTAL,
       COUNT(*)                             AS REGISTROS
FROM WTH_HOURLY_FORECAST
WHERE ID_LOCATION = :id_location
  AND DT_FORECAST >= ADD_MONTHS(TRUNC(SYSDATE,'MM'), -12)
GROUP BY TO_CHAR(DT_FORECAST,'YYYY-MM')
ORDER BY MES;

-- 1.5 Dataset ML com lags e rolling windows
SELECT
    TO_NUMBER(TO_CHAR(DT_FORECAST,'HH24'))  AS HORA,
    TO_NUMBER(TO_CHAR(DT_FORECAST,'D'))     AS DIA_SEMANA,
    TO_NUMBER(TO_CHAR(DT_FORECAST,'MM'))    AS MES,
    NR_TEMPERATURE_2M, NR_PRECIPITATION, NR_PRECIP_PROB,
    NR_HUMIDITY, NR_DEWPOINT, NR_PRESSURE_MSL, NR_CLOUDCOVER,
    NR_WINDSPEED_10M, NR_UV_INDEX, NR_SHORTWAVE_RAD,
    -- Lag features
    LAG(NR_TEMPERATURE_2M, 1)  OVER(PARTITION BY ID_LOCATION ORDER BY DT_FORECAST) AS TEMP_LAG_1H,
    LAG(NR_TEMPERATURE_2M, 6)  OVER(PARTITION BY ID_LOCATION ORDER BY DT_FORECAST) AS TEMP_LAG_6H,
    LAG(NR_TEMPERATURE_2M,24)  OVER(PARTITION BY ID_LOCATION ORDER BY DT_FORECAST) AS TEMP_LAG_24H,
    LAG(NR_PRECIPITATION,  1)  OVER(PARTITION BY ID_LOCATION ORDER BY DT_FORECAST) AS PRECIP_LAG_1H,
    -- Rolling mean 6h / 24h
    AVG(NR_TEMPERATURE_2M) OVER(PARTITION BY ID_LOCATION ORDER BY DT_FORECAST
        ROWS BETWEEN 5  PRECEDING AND CURRENT ROW) AS TEMP_ROLL_6H,
    AVG(NR_TEMPERATURE_2M) OVER(PARTITION BY ID_LOCATION ORDER BY DT_FORECAST
        ROWS BETWEEN 23 PRECEDING AND CURRENT ROW) AS TEMP_ROLL_24H,
    SUM(NR_PRECIPITATION)  OVER(PARTITION BY ID_LOCATION ORDER BY DT_FORECAST
        ROWS BETWEEN 23 PRECEDING AND CURRENT ROW) AS PRECIP_ROLL_24H
FROM WTH_HOURLY_FORECAST
WHERE ID_LOCATION = :id_location
  AND DT_FORECAST >= SYSDATE - :dias
ORDER BY DT_FORECAST;

-- 1.6 Estatísticas descritivas por variável (para normalização)
SELECT 'NR_TEMPERATURE_2M' AS VAR, ROUND(AVG(NR_TEMPERATURE_2M),3) AS MEDIA,
       ROUND(STDDEV(NR_TEMPERATURE_2M),3) AS DESVIO,
       MIN(NR_TEMPERATURE_2M) AS MINIMO, MAX(NR_TEMPERATURE_2M) AS MAXIMO
FROM WTH_HOURLY_FORECAST WHERE ID_LOCATION = :id_location UNION ALL
SELECT 'NR_HUMIDITY', ROUND(AVG(NR_HUMIDITY),3), ROUND(STDDEV(NR_HUMIDITY),3),
       MIN(NR_HUMIDITY), MAX(NR_HUMIDITY) FROM WTH_HOURLY_FORECAST WHERE ID_LOCATION = :id_location UNION ALL
SELECT 'NR_PRECIPITATION', ROUND(AVG(NR_PRECIPITATION),3), ROUND(STDDEV(NR_PRECIPITATION),3),
       MIN(NR_PRECIPITATION), MAX(NR_PRECIPITATION) FROM WTH_HOURLY_FORECAST WHERE ID_LOCATION = :id_location UNION ALL
SELECT 'NR_WINDSPEED_10M', ROUND(AVG(NR_WINDSPEED_10M),3), ROUND(STDDEV(NR_WINDSPEED_10M),3),
       MIN(NR_WINDSPEED_10M), MAX(NR_WINDSPEED_10M) FROM WTH_HOURLY_FORECAST WHERE ID_LOCATION = :id_location;

-- 1.7 Log de coletas recentes
SELECT l.NM_CITY, cl.NM_STATUS, cl.DT_COLLECTION, cl.NR_RECORDS, cl.DS_MESSAGE
FROM WTH_COLLECTION_LOG cl
JOIN WTH_LOCATIONS l ON l.ID_LOCATION = cl.ID_LOCATION
ORDER BY cl.DT_COLLECTION DESC
FETCH FIRST 50 ROWS ONLY;


